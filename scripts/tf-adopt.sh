#!/usr/bin/env bash
# Lab 7, Step 3b: read the real IDs of everything the spry-ai CloudFormation
# stack created, and write
#   infra/imports.tf      - one import block per resource
#   infra/terraform.tfvars - the values Terraform needs to describe them exactly
# Run it BEFORE the stack is deleted: the stack is where the IDs are recorded.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROJECT_NAME="${PROJECT_NAME:-spry}"
STACK="${PROJECT_NAME}-ai"
export AWS_DEFAULT_REGION="${AWS_REGION:-us-east-1}"

log() { printf '\033[36m==>\033[0m %s\n' "$*"; }
die() { printf '\033[31merror:\033[0m %s\n' "$*" >&2; exit 1; }

aws cloudformation describe-stacks --stack-name "${STACK}" >/dev/null 2>&1 \
  || die "stack ${STACK} not found - the IDs must be read before it is deleted"

ACCOUNT_ID="$(aws sts get-caller-identity --query Account --output text)"
log "account ${ACCOUNT_ID}, stack ${STACK}"

WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT

aws cloudformation describe-stack-resources --stack-name "${STACK}" --output json >"${WORK}/resources.json"
FUNCTION="${PROJECT_NAME}-agenda-parser"
aws lambda get-function --function-name "${FUNCTION}" --output json >"${WORK}/function.json"
aws lambda get-function-url-config --function-name "${FUNCTION}" --output json >"${WORK}/url.json"
aws ecr describe-repositories --repository-names "${FUNCTION}" --output json >"${WORK}/ecr.json" \
  || die "ECR repository ${FUNCTION} not found"

ROLE="$(python3 -c '
import json, sys
for r in json.load(open(sys.argv[1]))["StackResources"]:
    if r["LogicalResourceId"] == "Role":
        print(r["PhysicalResourceId"])
' "${WORK}/resources.json")"
[[ -n "${ROLE}" ]] || die "no Role in ${STACK}"
aws iam list-role-policies --role-name "${ROLE}" --output json >"${WORK}/inline.json"

python3 - "${WORK}" "${ROOT}/infra" "${PROJECT_NAME}" "${ACCOUNT_ID}" <<'PY'
import json, os, sys

work, infra, project, account = sys.argv[1:5]
load = lambda name: json.load(open(os.path.join(work, name)))

physical = {r["LogicalResourceId"]: r["PhysicalResourceId"]
            for r in load("resources.json")["StackResources"]}
function = load("function.json")
url = load("url.json")
inline = load("inline.json")["PolicyNames"]

role = physical["Role"]
fn = f"{project}-agenda-parser"
expect = {
    "Function": fn,
    "LogGroup": f"/aws/lambda/{fn}",
    "Budget": f"{project}-monthly",
}
for logical, name in expect.items():
    got = physical.get(logical)
    if got != name:
        sys.exit(f"error: {logical} is {got!r}, the Terraform code expects {name!r}")
if "invoke-bedrock" not in inline:
    sys.exit(f"error: role {role} has no inline policy invoke-bedrock ({inline})")

imports = [
    ("aws_ecr_repository.parser", fn),
    ("aws_iam_role.parser", role),
    ("aws_iam_role_policy_attachment.parser_logs",
     f"{role}/arn:aws:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole"),
    ("aws_iam_role_policy.parser_bedrock", f"{role}:invoke-bedrock"),
    ("aws_cloudwatch_log_group.parser", f"/aws/lambda/{fn}"),
    ("aws_lambda_function.parser", fn),
    ("aws_lambda_function_url.parser", fn),
    ("aws_budgets_budget.monthly", f"{account}:{project}-monthly"),
]
with open(os.path.join(infra, "imports.tf"), "w") as f:
    f.write("# Lab 7, Step 3b: hand the resources the spry-ai stack created to Terraform.\n")
    f.write("# Generated by scripts/tf-adopt.sh. Delete this file once the import is applied.\n")
    for to, rid in imports:
        f.write(f'\nimport {{\n  to = {to}\n  id = "{rid}"\n}}\n')

origins = list(dict.fromkeys(url.get("Cors", {}).get("AllowOrigins", [])))
values = {
    "project_name": project,
    "parser_role_name": role,
    "parser_image_uri": function["Code"]["ImageUri"],
    "parser_model": function["Configuration"]["Environment"]["Variables"]["PARSER_MODEL"],
    "allowed_origins": origins,
}
with open(os.path.join(infra, "terraform.tfvars"), "w") as f:
    f.write("# Non-secret values only. Secrets and personal data (budget_email) are\n")
    f.write("# variables of the HCP Terraform workspace, set by infra-bootstrap/.\n\n")
    width = max(len(k) for k in values)
    for key, value in values.items():
        f.write(f"{key.ljust(width)} = {json.dumps(value)}\n")

print(f"{len(imports)} import blocks -> infra/imports.tf")
print("values -> infra/terraform.tfvars")
PY

log "next: scripts/tf-release-cfn.sh, then: terraform -chdir=infra plan"
